"""Execution session, checkpointing and resume management for distributed workers."""

import datetime
import traceback
from typing import Dict, Any, List, Optional
from harness.core.config import get_node_id, DEFAULT_LEASE_MINUTES
from harness.core.task import Task
from harness.storage.state_store import StateStore

class SessionContext:
    """Active execution context for running a task with step-by-step checkpointing."""
    
    def __init__(self, task: Task, node_id: Optional[str] = None):
        self.task = task
        self.node_id = node_id or get_node_id()
        self.session_id = f"SESS-{datetime.datetime.now().strftime('%Y%m%d%H%M%S')}-{self.node_id[:8]}"
        self.start_time = datetime.datetime.now(datetime.timezone.utc).isoformat()
        self.checkpoint_data: Dict[str, Any] = {}
        self.step_history: List[Dict[str, Any]] = []
        
        # Load previous checkpoint if resuming
        existing_cp = StateStore.get_checkpoint(self.task.id)
        if existing_cp:
            self.checkpoint_data = existing_cp.get("data", {})
            self.step_history = existing_cp.get("step_history", [])
            self.task.current_step_index = existing_cp.get("current_step_index", self.task.current_step_index)

    def refresh_lease(self, minutes: int = DEFAULT_LEASE_MINUTES) -> None:
        """Extend lease duration on the active task."""
        now = datetime.datetime.now(datetime.timezone.utc)
        expires = now + datetime.timedelta(minutes=minutes)
        self.task.lease_expires_at = expires.isoformat()
        self.task.updated_at = now.isoformat()
        
        # Persist to active tasks store
        active = StateStore.get_active()
        active[self.task.id] = self.task.to_dict()
        StateStore.save_active(active)

    def checkpoint(
        self,
        step_index: int,
        step_name: str,
        data: Optional[Dict[str, Any]] = None,
        message: str = "",
    ) -> None:
        """
        Record an intermediate execution checkpoint.
        If the process dies or is transferred to another machine,
        execution will resume from this exact step and state.
        """
        now = datetime.datetime.now(datetime.timezone.utc)
        expires = now + datetime.timedelta(minutes=DEFAULT_LEASE_MINUTES)
        
        self.task.current_step_index = step_index
        self.task.status = "IN_PROGRESS"
        self.task.lease_expires_at = expires.isoformat()
        self.task.updated_at = now.isoformat()
        
        # Update step status in task steps if defined
        if 0 <= step_index < len(self.task.steps):
            self.task.steps[step_index]["status"] = "in_progress"
            # Mark previous steps as completed
            for i in range(step_index):
                self.task.steps[i]["status"] = "completed"

        if data:
            self.checkpoint_data.update(data)
            
        step_record = {
            "step_index": step_index,
            "step_name": step_name,
            "timestamp": now.isoformat(),
            "node_id": self.node_id,
            "session_id": self.session_id,
            "message": message,
        }
        self.step_history.append(step_record)
        
        # Save detailed checkpoint
        cp_payload = {
            "task_id": self.task.id,
            "task_title": self.task.title,
            "session_id": self.session_id,
            "node_id": self.node_id,
            "current_step_index": step_index,
            "current_step_name": step_name,
            "total_steps": self.task.total_steps,
            "progress_percent": self.task.progress_percentage,
            "updated_at": now.isoformat(),
            "data": self.checkpoint_data,
            "step_history": self.step_history,
            "artifacts": self.task.artifacts,
        }
        StateStore.save_checkpoint(self.task.id, cp_payload)
        
        # Update active task state
        active = StateStore.get_active()
        active[self.task.id] = self.task.to_dict()
        StateStore.save_active(active)

    def record_artifact(self, artifact_path: str) -> None:
        """Register a file or URL artifact generated by this task."""
        if artifact_path not in self.task.artifacts:
            self.task.artifacts.append(artifact_path)
            self.checkpoint(
                step_index=self.task.current_step_index,
                step_name=self.task.current_step_name,
                message=f"Registered artifact: {artifact_path}",
            )

    def complete(self, result_summary: str = "", artifacts: Optional[List[str]] = None) -> None:
        """Mark task as successfully completed across all systems."""
        now = datetime.datetime.now(datetime.timezone.utc).isoformat()
        self.task.status = "COMPLETED"
        self.task.completed_at = now
        self.task.updated_at = now
        self.task.current_step_index = len(self.task.steps)
        for s in self.task.steps:
            s["status"] = "completed"
            
        if artifacts:
            for art in artifacts:
                if art not in self.task.artifacts:
                    self.task.artifacts.append(art)
                    
        # Remove from active tasks
        active = StateStore.get_active()
        active.pop(self.task.id, None)
        StateStore.save_active(active)
        
        # Record into history
        history_entry = {
            **self.task.to_dict(),
            "result_summary": result_summary,
            "session_id": self.session_id,
            "completed_by_node": self.node_id,
            "start_time": self.start_time,
            "step_history": self.step_history,
        }
        StateStore.append_history(history_entry)
        
        # Clean up checkpoint
        StateStore.delete_checkpoint(self.task.id)

    def fail(self, error_message: str) -> None:
        """Record task failure with preserved checkpoint for inspection or retry."""
        now = datetime.datetime.now(datetime.timezone.utc).isoformat()
        self.task.status = "FAILED"
        self.task.last_error = error_message
        self.task.updated_at = now
        
        # Record error step in checkpoint
        self.checkpoint(
            step_index=self.task.current_step_index,
            step_name=f"Failed at: {self.task.current_step_name}",
            message=f"ERROR: {error_message}",
        )
        
        # Update active task
        active = StateStore.get_active()
        active[self.task.id] = self.task.to_dict()
        StateStore.save_active(active)

    def __enter__(self) -> "SessionContext":
        self.refresh_lease()
        return self

    def __exit__(self, exc_type, exc_val, exc_tb) -> bool:
        if exc_type is not None:
            # An unhandled exception or crash occurred: save interrupted checkpoint
            err = f"{exc_type.__name__}: {exc_val}\n" + "".join(traceback.format_tb(exc_tb))
            self.fail(err)
            return False  # re-raise exception
        return True
