    if r and r.status_code == 200:
        results = r.json()
        for t in results:
            if t['name'].strip() == clean_name:
                TAG_CACHE[clean_name] = t['id']
                return t['id']
    
    # Create tag
    r_create = safe_request(
        'post',
        "https://hosseinykala.ir/wp-json/wp/v2/tags",
        headers=HEADERS,
        json={'name': clean_name}
    )
    if r_create and r_create.status_code in [200, 201]:
        tid = r_create.json()['id']
        TAG_CACHE[clean_name] = tid
        return tid
    return None

