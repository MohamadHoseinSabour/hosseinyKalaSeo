def publish_all_clusters():
    load_tags()
    print(f"\n=== Publishing {len(SUB_ARTICLES)} Cluster Sub-Articles ===", flush=True)

    results = []
    for idx, sub in enumerate(SUB_ARTICLES, 1):
        print(f"\n[{idx}/{len(SUB_ARTICLES)}] Processing: {sub['title']}", flush=True)
        
        # Resolve tags
        t_ids = []
        for tname in sub['tag_names']:
            tid = resolve_tag(tname)
            if tid:
                t_ids.append(tid)

        payload = {
            'title': sub['title'],
            'slug': sub['slug'],
            'status': 'future',
            'date': sub['date'],
            'categories': sub['categories'],
            'tags': t_ids,
            'featured_media': sub['featured_media'],
            'excerpt': sub['excerpt'],
            'content': sub['content']
        }

        # Check existing
        existing_url = f"https://hosseinykala.ir/wp-json/wp/v2/posts?slug={sub['slug']}&status=any"
        r_chk = requests.get(existing_url, headers=HEADERS, auth=AUTH, timeout=20)
        p_id = None
        if r_chk.status_code == 200 and len(r_chk.json()) > 0:
            p_id = r_chk.json()[0]['id']
            print(f"  Existing post found (ID: {p_id}). Updating...", flush=True)
            r_post = requests.post(f"https://hosseinykala.ir/wp-json/wp/v2/posts/{p_id}", headers=HEADERS, auth=AUTH, json=payload, timeout=30)
        else:
            print(f"  Creating new post...", flush=True)
            r_post = requests.post("https://hosseinykala.ir/wp-json/wp/v2/posts", headers=HEADERS, auth=AUTH, json=payload, timeout=30)

        if r_post.status_code in [200, 201]:
            data = r_post.json()
            post_id = data.get('id')
            print(f"  [SUCCESS] Scheduled! ID: {post_id} | Date: {data.get('date')} | Link: {data.get('link')}", flush=True)
            results.append({'id': post_id, 'title': sub['title'], 'slug': sub['slug'], 'date': data.get('date')})

            # Update Rank Math meta
            meta_payload = {
                'meta': {
                    'rank_math_title': sub['meta_title'],
                    'rank_math_description': sub['meta_desc'],
                    'rank_math_focus_keyword': sub['focus_kw']
                }
            }
            r_meta = requests.post(f"https://hosseinykala.ir/wp-json/wp/v2/posts/{post_id}", headers=HEADERS, auth=AUTH, json=meta_payload, timeout=20)
            if r_meta.status_code == 200:
                print(f"  [META OK] Rank Math meta updated.", flush=True)
            else:
                print(f"  [META FAIL] HTTP {r_meta.status_code}", flush=True)
        else:
            print(f"  [FAILED] HTTP {r_post.status_code}: {r_post.text[:200]}", flush=True)

        time.sleep(1)

    print("\n=== Cluster Sub-Articles Summary ===", flush=True)
    for r in results:
        print(f"- ID: {r['id']} | Slug: {r['slug']} | Date: {r['date']} | Title: {r['title']}")

if __name__ == '__main__':
    publish_all_clusters()
